import sys, re
def esc(t):
    t = t.replace("&","&amp;").replace("<","&lt;").replace(">","&gt;").replace("'", "\\'").replace('"','\\"')
    # escape stray % not part of %n$x
    t = re.sub(r'%(?!\d\$[sd])', '%%', t)
    return t
