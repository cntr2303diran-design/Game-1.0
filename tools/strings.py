def esc(t):
    t = t.replace("&","&amp;").replace("<","&lt;").replace(">","&gt;").replace("'", "\\'").replace('"','\\"')
    # String berformat: % lepas ditulis %%. String tanpa argumen: dibiarkan (formatted="false").
    t = t.replace("\n", "\\n")
    if has_args(t):
        t = re.sub(r'%(?!\d\$[sd])', '%%', t)
    return t
